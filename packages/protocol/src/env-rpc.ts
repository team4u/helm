/**
 * Cross-platform compute node and remote execution environment RPC protocol (Hub ↔ BYOM node, WS + birpc).
 *
 * Aligned with `@earendil-works/pi-durable/env`'s `ExecutionEnv` (FileSystem + Shell);
 * binary content is always base64; errors are returned as the `RpcEnvError` structure
 * instead of being thrown. Also provides a generic local-machine IPC bridge
 * (`ipcCall` / `ipcSubscribe`) so optional plugins (e.g. `builtin:herdr`) can reuse
 * the node channel to reach Unix Sockets or Windows Named Pipes on the target
 * machine, eliminating SSH+Python entirely.
 */

/** Default local compute node ID (in-process with the Hub, zero network overhead). */
export const DEFAULT_NODE_ID = 'local'

/** Lightweight node health snapshot (collected by the node via Node.js native os + fs.statfs and piggybacked on register/heartbeat). */
export interface NodeHealthSnapshot {
  /** Collection timestamp (milliseconds). */
  collectedAt: number
  /** System uptime (seconds, os.uptime()). */
  uptimeSec: number
  /** 1 / 5 / 15 minute load averages (os.loadavg(); [0, 0, 0] on Windows). */
  loadAvg: [number, number, number]
  /** Free and total physical memory (bytes, os.freemem() / os.totalmem()). */
  memFreeBytes: number
  memTotalBytes: number
  /** Free and total disk space of the mount point holding the node's default directory (bytes, fs.promises.statfs). */
  diskFreeBytes?: number
  diskTotalBytes?: number
}

