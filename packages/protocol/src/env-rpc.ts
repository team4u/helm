export type RpcFileKind = 'file' | 'directory' | 'symlink'

/**
 * File operation error codes (aligned with pi-durable FileError.code; node upgrade
 * draining does not reject file operations, so this union has no node_draining —
 * draining applies only to new commands/IPC/tunnels).
 */
export type RpcFileErrorCode =
  | 'aborted'
  | 'not_found'
  | 'permission_denied'
  | 'not_directory'
  | 'is_directory'
  | 'invalid'
  | 'not_supported'
  | 'unknown'

/**
 * Execution error codes: `node_draining` means the node is draining for an
 * upgrade and rejects new commands (the daemon is still running and the
 * connection still up, just yielding to the upgrade) — strictly distinguished
 * from `aborted` (the user or host actively cancelling/terminating an in-flight
 * operation); upper layers must not fold it into cancellation.
 */
export type RpcExecutionErrorCode =
  | 'aborted'
  | 'node_draining'
  | 'timeout'
  | 'shell_unavailable'
  | 'spawn_error'
  | 'callback_error'
  | 'unknown'

