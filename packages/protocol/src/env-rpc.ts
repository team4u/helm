/**
 * Process facts for a single referencing path (a pre-deletion snapshot; locating
 * information only). Deliberately excludes cmdline / environ / argv — command
 * lines and environments often carry secrets, while occupancy determination
 * needs only the PID, process name and referencing path (cwd / open files).
 */
export interface NodePathUsageProcess {
  pid: number
  /** Process name (Linux /proc/<pid>/comm, world-readable; absent when the read fails). */
  name?: string
  /** Reference source: cwd (the process working directory is inside the target path) | fd (an open file/directory is inside the target path). */
  source: 'cwd' | 'fd'
  /** Absolute path on the referencing side (the real path of the cwd or fd; deleted files may carry a " (deleted)" suffix). */
  path: string
}

/**
 * Snapshot of processes on the node occupying a target absolute path (a
 * pre-deletion diagnostic surface, not a cross-process mutex).
 *
 * Honesty discipline: `complete=false` means "within the observable process set
 * there was a read anomaly or a scan cap was hit" — consumers must fail-closed
 * and never treat it as zero occupancy; `diagnostics` carries human-readable
 * incompleteness reasons (e.g. denied PIDs and their owner uid). Persistently
 * unreadable permission-style errno (EACCES/EPERM) is a structural blind spot
 * (across uid, or non-dumpable processes such as systemd --user — even the owner
 * cannot read them; any non-root scanner hits this), which no longer sets
 * `complete=false` regardless of uid; instead it is counted into `unobservable`
 * and presented truthfully in `diagnostics` — ordinary dumpable processes
 * sharing the Hub's uid (subagents/git/shells spawned by helm itself) remain
 * always observable, so the protection surface is unaffected; the consumer's
 * fail-closed discipline is unchanged. The snapshot is a one-shot pre-deletion
 * observation: processes started after the scan are outside the protection
 * (concurrent races genuinely exist).
 */
export interface NodePathUsage {
  /** The probed absolute path (the caller's input echoed verbatim). */
  path: string
  /** Hit process list (cap-truncation via processesTruncated; matchedTotal keeps the true count). */
  processes: NodePathUsageProcess[]
  /** True total of hit processes (deduplicated by PID: a process's cwd + multiple fds count once; unaffected by the processes truncation). */
  matchedTotal: number
  /** Whether the processes list was truncated by the reporting cap (when truncated, matchedTotal is still the deduplicated true value). */
  processesTruncated: boolean
  /** false = the scan is incomplete (anomaly within the observable set, or a cap was hit); must never be treated as zero occupancy. */
  complete: boolean
  /** Count of permission-unobservable processes (structural blind spots: cross-uid or non-dumpable; non-negative integer; deduplicated by PID; does not affect the complete verdict). */
  unobservable: number
  /** Incompleteness reasons and blind-spot diagnostics (human-readable; e.g. "pid 123 (uid 0): EACCES"). */
  diagnostics: string[]
}

