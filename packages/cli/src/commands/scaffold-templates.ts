/**
 * Backend for the app template: persistent public doc items + two dual-schema actions + main screen + sidebar shortcut.
 * Keeps parity with the app-builder skill fullstack-template.md:
 * flushes after write (honesty rule: never misreport persistence); zero Emoji; both input and output schemas declared
 * (single-source Schema contract; omissions fail at doctor register).
 */
export const SCAFFOLD_INDEX_TS_APP = (id: string, label: string) => `/**
 * Full-stack micro-app backend entrypoint (id: ${id}): export default PluginDefinition.
 * Re-check with \`helm apps validate\` after edits, then hot-publish with \`helm apps publish\`.
 */
import { randomUUID } from 'node:crypto'
import type { PluginDefinition } from '@helm/protocol'

interface Item {
  id: string
  title: string
  done: boolean
  createdAt: number
}

export default {
  id: '${id}',
  name: '${label}',
  description: 'Minimal full-stack micro-app: persistent items + add/toggle actions + main screen.',
  version: '0.1.0',
  clientRoot: './client',
  definePlugin(ctx) {
    // Persistent business data: public doc subscribed in real time by frontend usePluginDoc
    const items = ctx.doc<{ list: Item[] }>('items', { list: [] }, { public: true })

    // Shared outputSchema: actions return { ok: true }
    const okSchema = {
      type: 'object',
      properties: { ok: { type: 'boolean' } },
      required: ['ok'],
      additionalProperties: false,
    } as const

    ctx.action<{ title: string }, { ok: boolean }>({
      id: 'add_item',
      description: 'Add a new item',
      inputSchema: {
        type: 'object',
        properties: { title: { type: 'string', minLength: 1 } },
        required: ['title'],
        additionalProperties: false,
      },
      outputSchema: okSchema,
      exposeAsTool: true,
      async handler(input) {
        items.update((current) => ({
          list: [
            { id: randomUUID(), title: input.title, done: false, createdAt: Date.now() },
            ...current.list,
          ],
        }))
        await items.flush()
        return { ok: true }
      },
    })

    ctx.action<{ id: string; done: boolean }, { ok: boolean }>({
      id: 'set_done',
      description: 'Check or uncheck an item',
      inputSchema: {
        type: 'object',
        properties: { id: { type: 'string' }, done: { type: 'boolean' } },
        required: ['id', 'done'],
        additionalProperties: false,
      },
      outputSchema: okSchema,
      exposeAsTool: true,
      async handler(input) {
        items.update((current) => ({
          list: current.list.map((it) => (it.id === input.id ? { ...it, done: input.done } : it)),
        }))
        await items.flush()
        return { ok: true }
      },
    })

    // Full-stack app requirement: at least one ctx.ui.screen (checked by apps validate missing_app_screen)
    ctx.ui.screen({
      id: 'main',
      label: '${label}',
      client: { module: 'index.tsx', export: 'MainScreen' },
    })

    // Sidebar shortcut (protocol allows screen:<pluginId>/<screenId> targets; optional and removable,
    // app remains accessible from the App Center)
    ctx.ui.sidebarItem({
      id: 'open-main',
      label: '${label}',
      icon: 'layout-grid',
      target: 'screen:${id}/main',
    })
  },
} satisfies PluginDefinition
`

/**
 * Frontend for the app template: uses only @helm/plugin-client host primitives (Screen/ScreenSection/KvGrid/
 * DataTable/Checkbox) + host CSS variables and .btn styles; zero Emoji; 13px body text.
 */
export const SCAFFOLD_CLIENT_APP_TSX = `import { useState, type ReactNode } from 'react'
import {
  usePluginContext,
  usePluginDoc,
  Screen,
  ScreenSection,
  DataTable,
  KvGrid,
  Checkbox,
} from '@helm/plugin-client'
import './styles.css'

interface Item {
  id: string
  title: string
  done: boolean
  createdAt: number
}

export function MainScreen(): ReactNode {
  const { callAction, notify } = usePluginContext()
  const doc = usePluginDoc<{ list: Item[] }>('items')
  const [draft, setDraft] = useState('')
  const [pending, setPending] = useState(false)

  const list = doc?.list ?? []
  const doneCount = list.filter((it) => it.done).length

  const add = async () => {
    const title = draft.trim()
    if (title === '') return
    setPending(true)
    try {
      await callAction('add_item', { title })
      setDraft('')
    } catch (err) {
      notify('Failed to add item: ' + (err instanceof Error ? err.message : String(err)), 'error')
    } finally {
      setPending(false)
    }
  }

  return (
    <Screen title="Items Workbench" subtitle={'Completed ' + doneCount + ' / ' + list.length}>
      <ScreenSection title="Add Item">
        <div className="app-form">
          <input
            className="app-input"
            value={draft}
            placeholder="Enter item title and press Enter..."
            onChange={(e) => setDraft(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter') void add()
            }}
          />
          <button type="button" className="btn btn-primary" disabled={pending} onClick={() => void add()}>
            Add
          </button>
        </div>
      </ScreenSection>

      <ScreenSection title="Overview">
        <KvGrid
          items={[
            { key: 'Total items', value: list.length },
            { key: 'Completed', value: doneCount },
            { key: 'Data source', value: "public doc 'items' (live usePluginDoc subscription)" },
          ]}
        />
      </ScreenSection>

      <ScreenSection title="Item List">
        <DataTable
          loading={doc === undefined}
          empty={list.length === 0}
          emptyLabel="No items yet; enter a title above to add one"
          columns={2}
          label="Item List"
        >
          <thead>
            <tr>
              <th>Status</th>
              <th>Content</th>
            </tr>
          </thead>
          <tbody>
            {list.map((it) => (
              <tr key={it.id}>
                <td className="app-col-check">
                  <Checkbox
                    checked={it.done}
                    onChange={(checked) => {
                      void callAction('set_done', { id: it.id, done: checked }).catch((err: unknown) =>
                        notify('Failed to update item: ' + (err instanceof Error ? err.message : String(err)), 'error'),
                      )
                    }}
                  />
                </td>
                <td className={it.done ? 'app-done' : ''}>{it.title}</td>
              </tr>
            ))}
          </tbody>
        </DataTable>
      </ScreenSection>
    </Screen>
  )
}
`

