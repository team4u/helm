/**
 * One-shot Q&A command: helmx ask = create conversation + submit input + wait for answer.
 * Reuses existing endpoints (POST /api/conversations + POST .../input?wait=1) with no new HTTP routes.
 * stdout outputs only the answer text by default (script/pipeline-friendly); on error, keeps the conversation and includes its ID in the error message for inspection.
 */
import type { ConversationInputResult, ConversationSummary } from '@helmx/protocol'
import { CliError } from '../errors.js'
import { flagValue, parseFlags, type FlagSpec } from '../args.js'
import type { CommandContext, CommandSpec } from './shared.js'
import { assertNoExtraPositionals, coerceTags, printPlainText, printResult } from './shared.js'

const askFlags: FlagSpec[] = [
  { name: 'profile', type: 'string', help: 'Profile ID to use' },
  { name: 'title', type: 'string', help: 'conversation title (auto-generated by server by default; useful for tracking)' },
  { name: 'cwd', type: 'string', help: 'conversation working directory (absolute path)' },
  { name: 'model', type: 'string', help: 'explicit model override (provider/model)' },
  { name: 'tags', type: 'string', help: 'conversation tags (JSON array or comma-separated)' },
  { name: 'timeout', type: 'number', help: 'timeout in milliseconds while waiting for an answer (unlimited by default)' },
  { name: 'delete-on-success', type: 'boolean', help: 'delete the conversation after receiving an answer; keep for diagnostics on any failure' },
]

/** Combine prompt from positional arguments and piped stdin separated by a blank line, skipping empty/whitespace-only parts. */
function combinePrompt(positional: string | undefined, stdinText: string | undefined): string {
  const parts: string[] = []
  if (positional !== undefined && positional.trim() !== '') parts.push(positional)
  if (stdinText !== undefined && stdinText.trim() !== '') parts.push(stdinText)
  return parts.join('\n\n')
}

/**
 * Append conversation cleanup/inspection hints and attach conversationId after failure
 * (once created, the conversation is always preserved and never silently cleaned up).
 * Preserves original code/exitCode and merges conversationId into details for script callers.
 */
function rethrowWithConversation(err: unknown, conversationId: number, lead: string): never {
  const hint = `${lead} (conversation #${conversationId} kept: run helmx conversations get ${conversationId} to inspect / helmx conversations delete ${conversationId} to clean up)`
  if (err instanceof CliError) {
    const base = err.details !== null && typeof err.details === 'object' && !Array.isArray(err.details)
      ? { ...(err.details as Record<string, unknown>) }
      : {}
    base.conversationId = conversationId
    throw new CliError(`${err.message}${hint}`, err.code, err.exitCode, base)
  }
  throw new CliError(`${err instanceof Error ? err.message : String(err)}${hint}`, 'internal_error', 1, {
    conversationId,
  })
}

/**
 * Strictly validate wait response at boundary: text is the authoritative protocol answer
 * (redacted by kernel secretStash before returning); CLI never reconstructs it from entry.model.
 * Any malformed shape throws explicit invalid_response (with conversationId in details).
 */
function validateWaitResult(raw: unknown, conversationId: number): ConversationInputResult {
  const invalid = (reason: string): CliError =>
    new CliError(`Hub wait response is invalid: ${reason}`, 'invalid_response', 1, { conversationId })
  if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) {
    throw invalid(`must be JSON object, got ${raw === null ? 'null' : Array.isArray(raw) ? 'array' : typeof raw}`)
  }
  const r = raw as Record<string, unknown>
  if (typeof r.conversationId !== 'number' || r.conversationId !== conversationId) {
    throw invalid(`conversationId should be ${conversationId}, got ${JSON.stringify(r.conversationId)}`)
  }
  if (typeof r.submissionId !== 'string' || r.submissionId === '') throw invalid('submissionId must be a non-empty string')
  if (typeof r.text !== 'string') throw invalid(`text must be a string (allows empty string), got ${typeof r.text}`)
  const entry = r.entry
  if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) throw invalid('entry must be JSON object')
  const e = entry as Record<string, unknown>
  if (typeof e.id !== 'string' || e.id === '') throw invalid('entry.id must be a non-empty string')
  if (typeof e.kind !== 'string' || e.kind === '') throw invalid('entry.kind must be a non-empty string')
  return raw as ConversationInputResult
}

export function askCommands(): CommandSpec[] {
  return [
    {
      path: ['ask'],
      description: 'One-shot Q&A: create a conversation, submit input, and wait for an answer (combines stdin with prompt)',
      flags: askFlags,
      positional: '[text]',
      async run(ctx: CommandContext) {
        const parsed = parseFlags(askFlags, ctx.args)
        assertNoExtraPositionals(parsed.positionals, 1)
        const timeoutMs = flagValue<number>(parsed.flags, 'timeout')
        if (timeoutMs !== undefined && (!Number.isInteger(timeoutMs) || timeoutMs <= 0)) {
          throw new CliError(`--timeout must be a positive integer in milliseconds, got "${timeoutMs}"`, 'invalid_flag_value')
        }
        // prompt = positional arguments + piped stdin (read only when not a TTY; at least one non-whitespace part required)
        const stdinText = ctx.io.stdin.isTTY ? undefined : await ctx.io.stdin.readAll()
        const prompt = combinePrompt(parsed.positionals[0], stdinText)
        if (prompt === '') {
          throw new CliError('missing prompt: provide <text> positional argument or pipe input via stdin', 'empty_input')
        }

        // 1) Create conversation (no conversation exists yet on failure, so rethrow directly)
        const createBody: Record<string, unknown> = {}
        for (const [flag, key] of [
          ['title', 'title'],
          ['profile', 'profileId'],
          ['cwd', 'cwd'],
          ['model', 'model'],
        ] as const) {
          const v = flagValue<string>(parsed.flags, flag)
          if (v !== undefined) createBody[key] = v
        }
        const tags = flagValue<string>(parsed.flags, 'tags')
        if (tags !== undefined) createBody.tags = coerceTags(tags)
        const hub = await ctx.hub()
        const created = await hub.post<ConversationSummary>('/api/conversations', createBody)
        if (
          created === null || typeof created !== 'object' ||
          typeof created.id !== 'number' || !Number.isSafeInteger(created.id) || created.id <= 0
        ) {
          throw new CliError('Hub create conversation response is missing a valid positive integer id', 'invalid_response')
        }
        const conversationId = created.id

        // 2) Submit and wait for answer (whenBusy:reject — a brand-new conversation cannot have an active turn; fail explicitly if busy)
        let result: ConversationInputResult
        try {
          const raw = await hub.request<unknown>(
            'POST',
            `/api/conversations/${conversationId}/input?wait=1`,
            { body: { text: prompt, whenBusy: 'reject' }, timeoutMs: timeoutMs ?? 0 },
          )
          result = validateWaitResult(raw, conversationId)
        } catch (err) {
          rethrowWithConversation(err, conversationId, '')
        }

        // 3) Optional: delete conversation only after wait response validates; keep conversation and fail explicitly if deletion fails
        let deleted = false
        if (parsed.flags.get('delete-on-success') === true) {
          try {
            await hub.delete(`/api/conversations/${conversationId}`)
            deleted = true
          } catch (err) {
            rethrowWithConversation(err, conversationId, 'answer received, but failed to delete conversation')
          }
        }

        const answer = result.text
        if (ctx.json) {
          printResult(ctx, {
            conversationId,
            submissionId: result.submissionId,
            entryId: result.entry.id,
            answer,
            deleted,
          })
          return
        }
        // Human mode: stdout outputs only the answer text (empty string if empty; never fabricate content)
        if (answer !== '') printPlainText(ctx, answer)
      },
    },
  ]
}
